import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
const source = new URL('./', import.meta.url);
const assets = new URL('public/icons/lucide/', root);
const check = process.argv.includes('--check');
const mapping = JSON.parse(await readFile(new URL('lucide-map.json', source), 'utf8'));
const groups = new Map();
for (const [alias, name] of Object.entries(mapping)) {
    if (!/^fa-[a-z0-9-]+$/.test(alias) || !/^[a-z0-9-]+$/.test(name)) {
        throw new Error(`Invalid icon mapping: ${alias} -> ${name}`);
    }
    if (!groups.has(name)) groups.set(name, []);
    groups.get(name).push(alias);
}

const names = [...groups.keys()].sort();
let css = '/* Generated by node src/chlolirium/build-icons.mjs. Lucide 1.58.0; see public/icons/lucide/LICENSE. */\n';
css += 'html[data-icon-set="lucide"] {\n';
for (const name of names) {
    const svg = (await readFile(new URL(`${name}.svg`, assets), 'utf8'))
        .replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
    if (!svg.startsWith('<svg ') || !svg.endsWith('</svg>') || /<(?:script|foreignObject)\b/i.test(svg)) {
        throw new Error(`Invalid bundled SVG: ${name}`);
    }
    css += `    --cl-lucide-${name}: url("data:image/svg+xml,${encodeURIComponent(svg)}");\n`;
}
css += '}\n\n';
for (const [name, aliases] of groups) {
    css += [...aliases, `cl-icon-${name}`].map(alias => `.${alias}`).join(', ') + ` { --cl-icon: var(--cl-lucide-${name}); }\n`;
}
css += '\n';
css += ['html[data-icon-set="lucide"] .cl-icon::before', ...Object.keys(mapping)
    .map(alias => `html[data-icon-set="lucide"] .${alias}:not(.fa-brands, .fab)::before`)].join(',\n');
css += ` {
    content: "";
    display: inline-block;
    width: 1em;
    height: 1em;
    vertical-align: -0.125em;
    background-color: currentColor;
    -webkit-mask: var(--cl-icon) center / contain no-repeat;
    mask: var(--cl-icon) center / contain no-repeat;
    pointer-events: none;
}\n\n`;
css += await readFile(new URL('icons.css', source), 'utf8');

const catalog = [...groups].sort(([a], [b]) => a.localeCompare(b))
    .map(([name, aliases]) => ({ name, aliases }));
for (const [relative, content] of [
    ['public/css/chlolirium-icons.css', css],
    ['public/icons/lucide/catalog.json', JSON.stringify(catalog, null, 4) + '\n'],
]) {
    const target = new URL(relative, root);
    if (check) {
        if (await readFile(target, 'utf8') !== content) throw new Error(`Regenerate ${fileURLToPath(target)}`);
    } else {
        await writeFile(target, content);
    }
}
console.info(`${check ? 'Checked' : 'Generated'} ${groups.size} Lucide icons (${Object.keys(mapping).length} legacy aliases).`);
